#!/usr/bin/env python3
"""Generate hud/layouts/mtpms.json: the M theme with the TPMS block in the
right-hand info column.

m.json itself is generated by gen_m.py; this script reads the *built* m.json and
appends the tyre block, so the M theme keeps its own single source of truth.

The block is sized from the baked atlases (m_pt for the digits, m_pu for
psi / °C) and placed inside BOX, the area the four setup rows used to occupy.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.join(HERE, '..', 'apps', 'cluster_themes')
SRC = os.path.join(APP, 'hud', 'layouts', 'm.json')
OUT = os.path.join(APP, 'hud', 'layouts', 'mtpms.json')
FONTS = os.path.join(APP, 'hud', 'fonts')

BOX = (1428, 196, 316, 276)          # x, y, w, h - the band the setup rows used
DIGIT, UNIT = 'm_pt', 'm_pu'
TOP = [236, 240, 244, 255]           # numbers, as in the M theme
HEAD = [150, 158, 170, 255]          # wheel + units, a step dimmer
LINE = [150, 158, 170, 255]
BG = [6, 8, 11, 255]


def atlas(name):
    with open(os.path.join(FONTS, name + '.json'), encoding='utf-8') as f:
        return json.load(f)


def advance(font, text):
    g = font['glyphs']
    return sum(g[c]['advance'] for c in text if c in g)


def ink(font, text):
    """Top and bottom of the ink of `text` inside the cell."""
    g, cell = font['glyphs'], font['cellHeight']
    tops, bots = [], []
    for c in text:
        if c not in g:
            continue
        y = g[c]['y'] - (g[c]['y'] // cell) * cell
        tops.append(y)
        bots.append(y + g[c]['h'])
    if not tops:
        return 0, cell
    return min(tops), max(bots)


def main():
    d = json.load(open(SRC, encoding='utf-8'))
    digits, unit = atlas(DIGIT), atlas(UNIT)
    d_cell = digits['cellHeight']
    p = round(d_cell * 1.45)                     # row pitch of one reading
    adv = advance(digits, '88') / 2              # one digit
    pair_lead = round(1.02 * d_cell)             # temperature line's gap under the pressure one
    pair_h = pair_lead + d_cell
    pair_gap = round(0.30 * d_cell)              # air between the two axles' pairs
    col_w = 2 * adv + round(0.80 * d_cell)        # wide enough for "2.3" centred, not just for two digits
    gap = round(0.34 * p)
    clear = round(0.16 * p)
    head_w = round(d_cell * 0.95)
    u_top, u_bot = ink(unit, 'psi')
    t_top, t_bot = ink(unit, 'C')
    cell_u = unit['cellHeight']
    head_h = (u_bot + 1 - t_top) + cell_u        # psi box, then the °C box underneath
    head_gap = round(0.62 * p)

    x, y, bw, bh = BOX
    # The car has to be long enough to hold the two axles apart: each corner's pair is centred on its
    # wheel, and the pairs must not touch, so the axle spacing (0.5 * car_len) has to exceed
    # pair_h + pair_gap.
    # The car must stay near the size it is in the TPMS theme (53x101) — it is a 46x89 photo sprite, so
    # anything much larger smears. 1.19x still keeps the two axles far enough apart for the pairs.
    car_len = 42
    car_w = max(8, round(car_len * 53 / 101))
    block_w = 2 * col_w + 2 * gap + car_w
    tail = round(0.58 * p)                     # room under the car for the bottom of the cross
    air = round(0.55 * d_cell)                 # gap between a pair and the cross
    content_h = max(car_len, 2 * (air + pair_h))   # the pairs, not the car, decide the height
    block_h = head_h + head_gap + content_h + tail

    left = x + (bw - block_w) // 2
    top = y + (bh - block_h) // 2
    cx = left + block_w // 2
    car_x = cx - car_w // 2
    car_top = top + head_h + head_gap + (content_h - car_len) // 2
    r1 = car_top
    axle_box = {'FL': 0.182, 'FR': 0.182, 'RL': 0.682, 'RR': 0.682}
    # Where car-photo itself paints the tyres (`tyres` in sprites/car-photo.json): the left pair starts at
    # the very edge (0.0) while the right pair starts at 0.7174, and the two patches are not the same width.
    # The capsule is centred *inside* its patch, otherwise it sits on the patch's outer edge and the whole
    # car reads as if the wheels had slid left.
    patch = {'FL': (0.0, 0.3043), 'FR': (0.7174, 0.2826), 'RL': (0.0, 0.3043), 'RR': (0.7174, 0.2826)}
    box_y, box_h = 0.1591, 0.2841
    # The car sprite paints its own tyres; our capsules must sit inside those patches, so they are
    # sized from the patch and inset, not from the whole body.
    tyre_w = max(5, round(0.62 * patch['FL'][1] * car_w))
    tyre_h = max(8, round(0.86 * box_h * car_len))
    rule_y = car_top + car_len // 2                        # the cross sits on the car's centre line
    # The pairs hang off the rule, not off the axles: each corner's two readings stay a fixed distance from
    # the cross, so shrinking the car can never squeeze them against it.
    pair_top = {'FL': rule_y - air - pair_h, 'FR': rule_y - air - pair_h,
                'RL': rule_y + air, 'RR': rule_y + air}
    axle_y = {c: pair_top[c] + pair_h / 2 for c in axle_box}
    ink_l = left                                   # the reference's rule runs the block's width, between the
    ink_r = left + block_w                         # two pairs' rows
    col_l = left + col_w
    col_r = left + col_w + gap + car_w + gap

    head_top = top
    v_top = rule_y - car_len // 2 - 4
    v_bottom = rule_y + car_len // 2 + 4
    stop_l = car_x - clear
    stop_r = car_x + car_w + clear
    axis = car_x + (car_w - 1) // 2

    w = []
    w.append({'id': 'tp-rules-h-left', 'type': 'fill', 'z': 2,
              'x': ink_l, 'y': rule_y, 'w': stop_l - ink_l, 'h': 2, 'color': LINE})
    w.append({'id': 'tp-rules-h-right', 'type': 'fill', 'z': 2,
              'x': stop_r, 'y': rule_y, 'w': ink_r - stop_r, 'h': 2, 'color': LINE})
    # the vertical rules end on the readings themselves: from the first row's top to the last row's bottom,
    # never above the "2.3" nor below the "27"
    ink_top = pair_top['FL']
    ink_bot = pair_top['RL'] + pair_lead + d_cell
    vtop_y = ink_top
    w.append({'id': 'tp-rules-v-top', 'type': 'fill', 'z': 2,
              'x': axis, 'y': vtop_y, 'w': 2,
              'h': max(2, (car_top - 4) - vtop_y), 'color': LINE})
    vbot_y = car_top + car_len + 4
    w.append({'id': 'tp-rules-v-bottom', 'type': 'fill', 'z': 2,
              'x': axis, 'y': vbot_y, 'w': 2,
              'h': max(2, ink_bot - vbot_y), 'color': LINE})
    w.append({'id': 'tp-car', 'type': 'sprite', 'name': 'car-photo', 'z': 3,
              'x': car_x, 'y': car_top, 'w': car_w, 'h': car_len})

    glyph = round(d_cell * 0.95)
    word = round(advance(unit, 'bar'))
    total = glyph + 5 + word
    head_x = axis - total // 2
    w.append({'id': 'tp-head', 'type': 'sprite', 'name': 'wheel', 'z': 4, 'color': HEAD,
              'x': head_x,
              'y': head_top + (u_top + u_bot) // 2 - glyph // 2,
              'w': glyph, 'h': glyph})
    w.append({'id': 'tp-unit-p', 'type': 'text', 'z': 4,
              'x': head_x + glyph + 5, 'y': head_top - u_top, 'w': word, 'h': unit['cellHeight'],
              'text': '{{u:pressure}}', 'font': UNIT, 'align': 'left', 'color': HEAD})
    w.append({'id': 'tp-unit-t', 'type': 'text', 'z': 4,
              'x': head_x + glyph + 5, 'y': head_top + u_bot + 1 - t_top, 'w': word,
              'h': unit['cellHeight'],
              'text': '{{u:temp}}', 'font': UNIT, 'align': 'left', 'color': HEAD})

    for corner, bx, by in (('FL', patch['FL'][0], box_y), ('FR', patch['FR'][0], box_y),
                           ('RL', patch['RL'][0], 0.6591), ('RR', patch['RR'][0], 0.6591)):
        w.append({'id': 'tp-tyre-' + corner.lower(), 'type': 'sprite', 'name': 'tyre', 'z': 5,
                  'x': round(car_x + bx * car_w + (patch[corner][1] * car_w - tyre_w) / 2),
                  'y': round(car_top + by * car_len),
                  'w': tyre_w, 'h': tyre_h, 'grade': 'tyre', 'corner': corner})

    axle_box = {'FL': box_y, 'FR': box_y, 'RL': 0.682, 'RR': 0.682}
    for corner, side, row in (('FL', 'l', 0), ('FR', 'r', 0),
                              ('RL', 'l', 2), ('RR', 'r', 2)):
        for kind, off, font_id, colour, extra in (
                ('P', 0, DIGIT, TOP, {'colorBy': 'tyre', 'corner': corner}),
                ('T', pair_lead, DIGIT, TOP, {})):
            wx = col_l - col_w if side == 'l' else col_r
            align = 'center'
            box = {'id': 'tp-%s%s' % (kind.lower(), corner.lower()), 'type': 'text', 'z': 5,
                   'x': wx, 'y': pair_top[corner] + off, 'w': col_w, 'h': round(1.25 * d_cell),
                   'text': '{{tyre%s:%s}}' % (kind, corner), 'font': font_id,
                   'align': align, 'color': colour}
            box.update(extra)
            w.append(box)

    d['name'] = 'M + TPMS'
    d['_about'] = ('M theme with the TPMS block in the info column. Generated by '
                   'design/gen_mtpms.py from m.json; edit that script, not this file.')
    # The four setup rows live in two places: their own widgets, and the `segbars` inside the two mdash
    # backdrops. Both go, so the TPMS block needs no opaque backing to hide them.
    # --- the factory M3 look -------------------------------------------------
    # 1. The reference dial runs 0..8 x1000, so the shader's tick count (max / 1000) has to be 8,
    #    and the numeral at the top tick is 8, not 7.
    # 2. The reference band is a narrower ribbon than the M theme's wedge.
    # 3. Its numerals are a little larger.
    # The reference's fuel/oil brackets are smaller and thinner than the M theme's: the MDASH shader scales the
    # whole bracket off the radius (`kd = u_gaugeL.z / 120.0`), so a smaller r is also a thinner arc.
    for x in d['widgets']:
        if x['type'] == 'mdash':
            for k in ('gaugeL', 'gaugeR'):
                g = x.get(k)
                if isinstance(g, dict):
                    g['r'] = 112

    for x in d['widgets']:
        if x['type'] == 'mdash':
            x['style'] = 'm3'
            x['inner'] = 176                       # a slimmer bracket than the M8's 180                      # the M3's bracket: thin spine + tick ladder, no chrome bezel
        if x['type'] == 'mtach':
            # Scale 0..8 like the reference, red zone from the 7000 mark: _redMarks() takes
            # min(redline, max-500)/max = 7000/8000 = 0.875, so only the last eighth is red.
            x['max'] = 8000
            x['wTop'] = 8
            x['wBot'] = 15                       # a narrow ribbon, as the reference's, not the M's fat wedge
            x['style'] = 'm3'                      # two tick lengths and a hatched red zone
        elif x['id'].startswith(('nl', 'nr', 'mnl', 'mnr')):
            x['h'] = 42
            # the scale still ends at 8; the red zone starts at the 7000 mark      # the car redlines at 7000, so nothing above 7 is drawn

    drop = ('ico_', 'setup_', 'mico_', 'msetup_')
    d['widgets'] = [x for x in d['widgets'] if not x['id'].startswith(drop)]
    for x in d['widgets']:
        if x['type'] == 'mdash':
            x.pop('segbars', None)          # the bars live on the widget itself, not in params
    for x in d['widgets']:
        f = x.get('font')
        if f in ('m_num', 'm_speed', 'm_gear'):
            x['font'] = f + '_mf'          # this theme's numerals are microgrammafull
    for x in d['widgets']:
        if x['id'] == 'badge':
            # the reference's mark is the shader's tricolour with the M right after it,
            # not the long "BMW M3" string the stock theme prints under the stripes
            x['text'] = 'M'
            x['x'], x['y'], x['w'], x['h'] = 994, 66, 70, 44
            x['align'] = 'left'
            x['color'] = 'fg'
    for x in d['widgets']:
        if x.get('font') == 'm_num_mf' and x.get('text') == '7':
            x['text'] = '8'                # the reference dials' top mark
    d['widgets'] = d['widgets'] + w
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, separators=(',', ':'))
    print('wrote mtpms.json: %d widgets (+%d), block %dx%d at %d,%d'
          % (len(d['widgets']), len(w), block_w, block_h, left, top))


if __name__ == '__main__':
    main()
