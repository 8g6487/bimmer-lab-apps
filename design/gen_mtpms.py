#!/usr/bin/env python3
"""Generate hud/layouts/mtpms.json: the M theme with the TPMS block in the
right-hand info column.

m.json itself is generated by gen_m.py; this script reads the *built* m.json and
appends the tyre block, so the M theme keeps its own single source of truth.

The block is sized from the baked atlases (m_pt for the digits, m_pu for
psi / °C) and placed inside BOX, the area the four setup rows used to occupy.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.join(HERE, '..', 'apps', 'cluster_themes')
SRC = os.path.join(APP, 'hud', 'layouts', 'm.json')
OUT = os.path.join(APP, 'hud', 'layouts', 'mtpms.json')
FONTS = os.path.join(APP, 'hud', 'fonts')

BOX = (1428, 196, 316, 276)          # x, y, w, h - the band the setup rows used
DIGIT, UNIT = 'm_pt', 'm_pu'
TOP = [236, 240, 244, 255]           # numbers, as in the M theme
HEAD = [150, 158, 170, 255]          # wheel + units, a step dimmer
LINE = [108, 116, 128, 255]
BG = [6, 8, 11, 255]


def atlas(name):
    with open(os.path.join(FONTS, name + '.json'), encoding='utf-8') as f:
        return json.load(f)


def advance(font, text):
    g = font['glyphs']
    return sum(g[c]['advance'] for c in text if c in g)


def ink(font, text):
    """Top and bottom of the ink of `text` inside the cell."""
    g, cell = font['glyphs'], font['cellHeight']
    tops, bots = [], []
    for c in text:
        if c not in g:
            continue
        y = g[c]['y'] - (g[c]['y'] // cell) * cell
        tops.append(y)
        bots.append(y + g[c]['h'])
    if not tops:
        return 0, cell
    return min(tops), max(bots)


def main():
    d = json.load(open(SRC, encoding='utf-8'))
    digits, unit = atlas(DIGIT), atlas(UNIT)
    d_cell = digits['cellHeight']
    p = round(d_cell * 1.45)                     # row pitch
    adv = advance(digits, '88') / 2              # one digit
    rows = [0, p, round(2.52 * p), round(3.52 * p)]
    car_len = round(1.70 * p)
    car_w = max(8, round(car_len * 53 / 101))
    gap = round(0.52 * p)
    clear = round(0.30 * p)
    col_w = 2 * adv + round(0.40 * d_cell)
    block_w = 2 * col_w + 2 * gap + car_w
    head_w = round(d_cell * 0.95)
    u_top, u_bot = ink(unit, 'psi')
    t_top, t_bot = ink(unit, 'C')
    cell_u = unit['cellHeight']
    head_h = (u_bot + 6 - t_top) + cell_u        # psi box, then the °C box underneath
    head_gap = round(0.45 * p)
    block_h = head_h + head_gap + rows[3] + d_cell

    x, y, bw, bh = BOX
    left = x + (bw - block_w) // 2
    top = y + (bh - block_h) // 2
    cx = left + block_w // 2
    car_x = cx - car_w // 2
    r1 = top + head_h + head_gap
    rule_y = round(r1 + (rows[1] + rows[2]) / 2 + d_cell / 2)
    car_top = rule_y - car_len // 2
    ink_l = left
    col_l = left + col_w
    col_r = left + col_w + gap + car_w + gap
    ink_r = left + block_w
    head_top = top
    v_top = r1 + round(0.04 * d_cell)
    v_bottom = r1 + rows[3] + round(0.95 * d_cell)
    stop_l = car_x - clear
    stop_r = car_x + car_w + clear
    axis = car_x + (car_w - 1) // 2

    w = []
    w.append({'id': 'tp-rules-h-left', 'type': 'fill', 'z': 2,
              'x': ink_l, 'y': rule_y, 'w': stop_l - ink_l, 'h': 2, 'color': LINE})
    w.append({'id': 'tp-rules-h-right', 'type': 'fill', 'z': 2,
              'x': stop_r, 'y': rule_y, 'w': ink_r - stop_r, 'h': 2, 'color': LINE})
    w.append({'id': 'tp-rules-v-top', 'type': 'fill', 'z': 2,
              'x': axis, 'y': v_top, 'w': 2, 'h': car_top - clear - v_top, 'color': LINE})
    w.append({'id': 'tp-rules-v-bottom', 'type': 'fill', 'z': 2,
              'x': axis, 'y': car_top + car_len + clear, 'w': 2,
              'h': v_bottom - (car_top + car_len + clear), 'color': LINE})
    w.append({'id': 'tp-car', 'type': 'sprite', 'name': 'car-photo', 'z': 3,
              'x': car_x, 'y': car_top, 'w': car_w, 'h': car_len})

    glyph = round(d_cell * 0.95)
    word = round(advance(unit, 'bar'))
    total = glyph + 5 + word
    head_x = axis - total // 2
    w.append({'id': 'tp-head', 'type': 'sprite', 'name': 'wheel', 'z': 4, 'color': HEAD,
              'x': head_x,
              'y': head_top + (u_top + u_bot) // 2 - glyph // 2,
              'w': glyph, 'h': glyph})
    w.append({'id': 'tp-unit-p', 'type': 'text', 'z': 4,
              'x': head_x + glyph + 5, 'y': head_top - u_top, 'w': word, 'h': unit['cellHeight'],
              'text': '{{u:pressure}}', 'font': UNIT, 'align': 'left', 'color': HEAD})
    w.append({'id': 'tp-unit-t', 'type': 'text', 'z': 4,
              'x': head_x + glyph + 5, 'y': head_top + u_bot + 6 - t_top, 'w': word,
              'h': unit['cellHeight'],
              'text': '{{u:temp}}', 'font': UNIT, 'align': 'left', 'color': HEAD})

    tyre_w = max(5, round(0.19 * car_w))
    tyre_h = round(tyre_w * 2.3)
    box_x, box_w = 0.0, 0.261
    box_y, box_h = 0.182, 0.239
    for corner, bx, by in (('FL', box_x, box_y), ('FR', 1 - box_x - box_w, box_y),
                           ('RL', box_x, 0.682), ('RR', 1 - box_x - box_w, 0.682)):
        w.append({'id': 'tp-tyre-' + corner.lower(), 'type': 'sprite', 'name': 'tyre', 'z': 5,
                  'x': round(car_x + bx * car_w), 'y': round(car_top + by * car_len),
                  'w': tyre_w, 'h': tyre_h, 'grade': 'tyre', 'corner': corner})

    for corner, side, row in (('FL', 'l', 0), ('FR', 'r', 0),
                              ('RL', 'l', 2), ('RR', 'r', 2)):
        for kind, off, font_id, colour, extra in (
                ('P', 0, DIGIT, TOP, {'colorBy': 'tyre', 'corner': corner}),
                ('T', round(1.18 * d_cell), DIGIT, TOP, {})):
            if side == 'l':
                wx = col_l - col_w
            else:
                wx = col_r
            align = 'left'
            box = {'id': 'tp-%s%s' % (kind.lower(), corner.lower()), 'type': 'text', 'z': 5,
                   'x': wx, 'y': r1 + rows[row] + off, 'w': col_w, 'h': round(1.25 * d_cell),
                   'text': '{{tyre%s:%s}}' % (kind, corner), 'font': font_id,
                   'align': align, 'color': colour}
            box.update(extra)
            w.append(box)

    d['name'] = 'M + TPMS'
    d['_about'] = ('M theme with the TPMS block in the info column. Generated by '
                   'design/gen_mtpms.py from m.json; edit that script, not this file.')
    # The four setup rows live in two places: their own widgets, and the `segbars` inside the two mdash
    # backdrops. Both go, so the TPMS block needs no opaque backing to hide them.
    drop = ('ico_', 'setup_', 'mico_', 'msetup_')
    d['widgets'] = [x for x in d['widgets'] if not x['id'].startswith(drop)]
    for x in d['widgets']:
        if x['type'] == 'mdash':
            x.pop('segbars', None)          # the bars live on the widget itself, not in params
    d['widgets'] = d['widgets'] + w
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, separators=(',', ':'))
    print('wrote mtpms.json: %d widgets (+%d), block %dx%d at %d,%d'
          % (len(d['widgets']), len(w), block_w, block_h, left, top))


if __name__ == '__main__':
    main()
